import assert from 'node:assert/strict';
const base = process.env.SCIENCE_API_BASE ?? 'http://localhost:5000';
const check = async (path, status = 200, headers = {}) => {
  const response = await fetch(base + path, { headers, signal: AbortSignal.timeout(20000) });
  assert.equal(response.status, status, `${path}: HTTP ${response.status}`);
  return response;
};
const fullResponse = await check('/api/v2/elements/fe');
const fullText = await fullResponse.text();
const fe = JSON.parse(fullText);
assert.equal(fe.symbol, 'Fe');
assert.equal(fe.atomic_properties.atomic_mass, 55.845);
assert.deepEqual(fe.atomic_properties.electrons_per_shell, [2, 8, 14, 2]);
assert.equal(fe.isotopes.length, 4);
const summary = await (await check('/api/v2/elements/fe?view=summary')).text();
const fields = await (await check('/api/v2/elements/fe?fields=symbol,names.tr,atomic_properties.radii_pm')).text();
assert.ok(summary.length < fullText.length * .4);
assert.deepEqual(Object.keys(JSON.parse(fields)), ['symbol', 'names', 'atomic_properties']);
const page = await (await check('/api/v2/elements?block=d&pageSize=3&fields=symbol&view=full')).json();
assert.equal(page.results.length, 3);
const next = await (await check(page.info.next)).json();
assert.equal(next.info.page, 2);
assert.deepEqual(Object.keys(next.results[0]), ['symbol']);
for (const q of ['?view=bogus', '?fields=missing&q=no-match', '?pageSize=101', '?page=-2']) await check('/api/v2/elements' + q, 400);
await check('/api/v2/elements/not-an-element', 404);
await check('/api/v2/elements/fe', 304, { 'If-None-Match': fullResponse.headers.get('etag') });
const publicGet = await check('/api/v2/elements/fe', 200, { Origin: 'https://example.net' });
assert.equal(publicGet.headers.get('access-control-allow-origin'), '*');
const preflight = await fetch(base + '/api/v2/elements', { method: 'OPTIONS', headers: { Origin: 'https://example.net', 'Access-Control-Request-Method': 'GET', 'Access-Control-Request-Headers': 'if-none-match' } });
assert.equal(preflight.status, 204);
assert.equal(preflight.headers.get('access-control-allow-origin'), '*');
const compressed = await check('/api/v2/elements?view=full&pageSize=100', 200, { 'Accept-Encoding': 'gzip' });
assert.equal(compressed.headers.get('content-encoding'), 'gzip');
const aspirin = await (await check('/api/v2/compounds/aspirin')).json();
assert.equal(aspirin.identifiers.pubchem_cid, 2244);
assert.equal(aspirin.molecular_properties.molecular_formula, 'C9H8O4');
assert.ok(aspirin.safety.toxicology.reported_values.length);
assert.equal(aspirin.safety.toxicology.ld50_oral_rat_mg_kg, null);
const compounds = await (await check('/api/v2/compounds?pageSize=100')).json();
assert.equal(compounds.info.count, 51);
const legacy = await (await check('/api/v1/elements/fe')).json();
assert.equal(legacy.symbol, 'Fe');
assert.ok(legacy.market);
const privateResponse = await check('/api/v1/me/wallet', 401, { Origin: 'https://example.net' });
assert.notEqual(privateResponse.headers.get('access-control-allow-origin'), '*');
console.log(JSON.stringify({ passed: true, elements: 118, compounds: 51, fullBytes: Buffer.byteLength(fullText), summaryBytes: Buffer.byteLength(summary), fieldsBytes: Buffer.byteLength(fields), summaryReduction: `${(100 * (1 - summary.length / fullText.length)).toFixed(1)}%`, checks: ['scientific facts', 'projection', 'pagination', '400/404', 'ETag 304', 'public CORS GET/preflight', 'gzip', 'aspirin', 'v1 compatibility', 'private route isolation'] }, null, 2));
